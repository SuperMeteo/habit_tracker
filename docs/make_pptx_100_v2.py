def dart_stats():
    files = [f for f in glob.glob(os.path.join(ROOT, "lib", "**", "*.dart"), recursive=True)
             if not f.endswith(".g.dart") and not f.endswith("main_demo.dart")]
    lines = 0
    for f in files:
        with open(f, encoding="utf-8", errors="replace") as fh:
            lines += sum(1 for _ in fh)
    return len(files), lines


def test_stats():
    files = sorted(glob.glob(os.path.join(ROOT, "test", "*.dart")))
    lines = 0
    for f in files:
        with open(f, encoding="utf-8", errors="replace") as fh:
            lines += sum(1 for _ in fh)
    return len(files), lines


