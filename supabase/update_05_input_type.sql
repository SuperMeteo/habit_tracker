-- ============================================================================
-- อัปเดตที่ 5 — habit ชนิด "เลือก 3 ระดับ" (น้อย / ปานกลาง / มาก)
--
-- เดิมแอปเดาชนิดจาก target_value: ว่าง = ติ๊ก, มีค่า = ตัวเลข
-- ซึ่งขยายเป็นชนิดที่ 3 ไม่ได้ จึงเพิ่มคอลัมน์บอกชนิดตรง ๆ
--
-- ค่าที่เป็นไปได้: 'check' | 'number' | 'scale3'
-- scale3 เก็บคำตอบไว้ในช่อง value เป็น 1 = น้อย, 2 = ปานกลาง, 3 = มาก
--
-- วิธีใช้: Supabase Dashboard → SQL Editor → New query → วางทั้งไฟล์ → Run
-- รันซ้ำได้ ไม่แตะข้อมูลเดิม
-- ============================================================================

alter table habits
  add column if not exists input_type text not null default 'check';

-- แถวเก่าที่มีเป้าหมายตัวเลขอยู่แล้ว ต้องถูกจัดเป็นชนิดตัวเลข
-- ถ้าไม่เติมย้อนหลัง เครื่องที่ดึงข้อมูลไปจะเห็นเป็น habit ติ๊กธรรมดา
-- แล้วช่องกรอกค่ากับกราฟจะหายไปทั้งที่ข้อมูลยังอยู่
update habits
   set input_type = 'number'
 where target_value is not null
   and input_type = 'check';

